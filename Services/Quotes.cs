    public static Quote ForUser(int userId, int cursor)
    {
        var n = All.Length;
        cursor = Math.Max(0, cursor);
        var round = cursor / n;
        var order = Order(userId, round);

        if (round > 0 && cursor % n == 0)
        {
            var previousLast = Order(userId, round - 1)[n - 1];
            if (order[0] == previousLast) return All[order[1]];
        }
        if (round > 0 && cursor % n == 1)
        {
            var previousLast = Order(userId, round - 1)[n - 1];
            if (order[0] == previousLast) return All[order[0]];
        }
        return All[order[cursor % n]];
    }

    private static int[] Order(int userId, int round)
    {
        var order = Enumerable.Range(0, All.Length).ToArray();
        var rng = new Random(unchecked(userId * 7919 + round * 104729 + 17));
        for (var i = order.Length - 1; i > 0; i--)
        {
            var j = rng.Next(i + 1);
            (order[i], order[j]) = (order[j], order[i]);
        }
        return order;
    }
